bot.on('text', async (ctx, next) => {
  const pending = richBuildPending.get(ctx.from.id);
  if (!pending || pending.stage !== 'text' || ctx.message.text.startsWith('/')) return next();
  const admin = richBuildIsAdmin(ctx);
  const mode = pending.mode;
  const cost = mode === 'clean' ? 1 : 2;
  if (!admin) {
    const credits = richBuildCredits.get(ctx.from.id) || 0;
    if (credits < cost) {
      richBuildPending.delete(ctx.from.id);
      await ctx.sendRichMessage(new HTML().heading(2, 'Kredit belum cukup')
        .paragraph(`Mode ini membutuhkan ${cost} kredit. Gunakan /topup untuk meminta kredit melalui QRIS dan tunggu konfirmasi admin.`)
        .table([['MODE', 'BIAYA'], ['Clean', '1 kredit'], ['Signature', '2 kredit']], { bordered: true, striped: true, hasHeader: true }).build());
      return;
    }
    richBuildCredits.set(ctx.from.id, credits - cost);
  }
  richBuildPending.delete(ctx.from.id);
  try {
    await ctx.sendRichMessage(richBuildTableMessage(ctx.message.text, mode === 'signature'));
    if (!admin) await ctx.sendRichMessage(new HTML().paragraph(`Sisa kredit: <b>${richBuildCredits.get(ctx.from.id) || 0}</b>`).build());
  } catch (e) {
    if (!admin) richBuildCredits.set(ctx.from.id, (richBuildCredits.get(ctx.from.id) || 0) + cost);
    await ctx.sendMessage('Gagal membuat Rich Message: ' + e.message);
  }
});

