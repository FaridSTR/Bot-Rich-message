const richBuildTableMessage = (raw, watermark = false) => {
  const lines = String(raw || '').split(/\r?\n/).map(s => s.trim()).filter(Boolean);
  const rows = [['FIELD', 'CONTENT']];
  for (const line of lines) {
    const split = line.split(/\s*\|\s*/);
    if (split.length >= 2) rows.push([split.shift().slice(0, 80), split.join(' | ').slice(0, 900)]);
    else rows.push(['', line.slice(0, 900)]);
  }
  const builder = new HTML()
    .heading(2, 'RICH MESSAGE')
    .table(rows, { bordered: true, striped: true, hasHeader: true });
  if (watermark) builder.paragraph(`<i>${richBuildWatermark()}</i>`);
  return builder.build();
};

